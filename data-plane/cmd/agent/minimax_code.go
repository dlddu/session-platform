// The minimax-code workload (docs/prd/minimax-code-workload.md, AC-G1~G4) runs
// the MiniMax Code CLI, `mcode exec`, on the claude-code runner. Everything in
// this file is the CLI-specific half; the queue, bounds, archive and resume
// flag are claudeWorkload's.
const (
	workloadMiniMaxCode = "minimax-code"

	// Keep in sync with control-plane/internal/adapter/k8s (MiniMaxCodeModelEnvVar).
	miniMaxModelEnv  = "MINIMAX_CODE_MODEL"
	miniMaxBinaryEnv = "MINIMAX_CODE_BIN"

	defaultMiniMaxBinary = "mcode"
	// miniMaxDefaultModel is what a platform-default session runs when the
	// Secret names no model. Claude Code has an installation default it can
	// fall back to by omitting --model; mcode resolves a model only through a
	// provider entry, so the platform has to name one (AC-G1).
	miniMaxDefaultModel = "MiniMax-M3.1-Flash"
	// miniMaxProviderID names the one provider entry the managed config
	// declares. The CLI addresses models as custom_provider:<id>/<model>.
	miniMaxProviderID = "session-platform"
	// miniMaxPermission is mcode's headless default, pinned so an upstream
	// default change cannot silently widen what an unattended run may do.
	miniMaxPermission = "smart"

	// The managed config lives beside the state tree, not in it: it is
	// regenerated by every pod from that pod's own environment, so it never
	// enters an archive and a restore can never bring back a stale one.
	miniMaxConfigDirName  = ".session-platform-mcode"
	miniMaxConfigFileName = "config.yaml"
)

// miniMaxCLI is the agentCLI for `mcode`. The provider it talks to is fixed at
// construction: the loopback credential proxy, with the non-secret placeholder
// as its key (AC-G3). mcode never sees a real credential, so nothing it writes
// into HOME — which it does freely — can carry one into an archive.
type miniMaxCLI struct {
	configPath  string
	baseURL     string
	placeholder string
	model       string
}

func newMiniMaxCLI(stateDir, model, baseURL, placeholder string) (miniMaxCLI, error) {
	abs, err := filepath.Abs(strings.TrimSpace(stateDir))
	if err != nil {
		return miniMaxCLI{}, fmt.Errorf("resolve minimax state dir: %w", err)
	}
	abs = filepath.Clean(abs)
	if abs == string(filepath.Separator) {
		return miniMaxCLI{}, errors.New("minimax state dir must not be the filesystem root")
	}
	return miniMaxCLI{
		configPath:  filepath.Join(filepath.Dir(abs), miniMaxConfigDirName, miniMaxConfigFileName),
		baseURL:     baseURL,
		placeholder: placeholder,
		model:       resolveMiniMaxModel(model),
	}, nil
}

// resolveMiniMaxModel turns the session's model setting into the concrete
// model mcode runs (AC-G1). An explicit model wins, exactly as in AC-E6.
func resolveMiniMaxModel(model string) string {
	if model == "" || model == platformDefaultModel {
		return miniMaxDefaultModel
	}
	return model
}

func (miniMaxCLI) workloadName() string { return workloadMiniMaxCode }

// argv is one non-interactive `mcode exec` run (AC-G2). The prompt goes after
// "--", so a prompt that starts with "--" is still a prompt and can never
// change a platform-controlled flag. --continue resumes the latest conversation
// of the workspace, which is the session's only one (AC-E4).
func (m miniMaxCLI) argv(binary, model, prompt string, resume bool) []string {
	argv := []string{binary, "exec",
		"--config", m.configPath,
		"--model", "custom_provider:" + miniMaxProviderID + "/" + resolveMiniMaxModel(model),
		"--permission", miniMaxPermission,
		"--output-format", "stream-json",
	}
	if resume {
		argv = append(argv, "--continue")
	}
	return append(argv, "--", prompt)
}

func (miniMaxCLI) newProjector(dst io.Writer) io.WriteCloser {
	return newMiniMaxStreamProjector(dst)
}

// ensureHome writes the managed config. HOME itself needs nothing from the
// platform: mcode creates its own data directory on first run.
func (m miniMaxCLI) ensureHome(string) error {
	content, err := m.renderConfig()
	if err != nil {
		return err
	}
	return writeMiniMaxConfig(m.configPath, content)
}

// validateState is the type-neutral half of AC-E5's integrity check. There is
// no platform-owned file in this type's HOME to insist on.
func (miniMaxCLI) validateState(root string) error {
	return validateRestoredAgentState(root)
}

// renderConfig is the whole config the CLI runs with. JSON is valid YAML, and
// encoding it with encoding/json means no value can break out of its field.
func (m miniMaxCLI) renderConfig() ([]byte, error) {
	config := map[string]any{
		"defaultModel":     "custom_provider:" + miniMaxProviderID + "/" + m.model,
		"dataContribution": map[string]any{"enabled": false},
		// The installed CLI is the image's pinned version; it must not replace
		// itself mid-session, as DISABLE_AUTOUPDATER guarantees for Claude.
		"promptConfig": map[string]any{"autoUpdate": false},
		"custom_provider": map[string]any{
			miniMaxProviderID: map[string]any{
				"name":    miniMaxProviderID,
				"kind":    "custom",
				"enabled": true,
				"api":     "anthropic-messages",
				"options": map[string]any{
					"baseURL":  m.baseURL,
					"authMode": "api-key",
					"apiKey":   m.placeholder,
				},
				"models": map[string]any{
					m.model: map[string]any{"reasoning": true},
				},
			},
		},
	}
	out, err := json.Marshal(config)
	if err != nil {
		return nil, fmt.Errorf("encode minimax config: %w", err)
	}
	return append(out, '\n'), nil
}

func writeMiniMaxConfig(path string, content []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return fmt.Errorf("create minimax config directory: %w", err)
	}
	f, err := os.CreateTemp(dir, ".config-*")
	if err != nil {
		return fmt.Errorf("create minimax config: %w", err)
	}
	tmp := f.Name()
	defer os.Remove(tmp)
	if err := f.Chmod(0o600); err != nil {
		f.Close()
		return err
	}
	if _, err := f.Write(content); err != nil {
		f.Close()
		return fmt.Errorf("write minimax config: %w", err)
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		return fmt.Errorf("install minimax config: %w", err)
	}
	return nil
}

// miniMaxCredentialEnv is every credential variable either CLI could pick up
// on its own, as of @minimax-ai/code 0.6.12 and the Claude names above. The
// control plane injects none of them; refusing to start on any is defence in
// depth, and the same list feeds output redaction.
var miniMaxCredentialEnv = []string{
	"ANTHROPIC_API_KEY", "ANTHROPIC_OAUTH_TOKEN", "ANTHROPIC_FOUNDRY_API_KEY",
	"CLAUDE_CODE_OAUTH_TOKEN", "K3S_MCP_TOKEN",
	"MINIMAX_API_KEY", "MINIMAX_CN_API_KEY", "MCODE_PROVIDER_API_KEY", "MAVIS_ACCESS_TOKEN",
	"OPENAI_API_KEY", "AWS_BEARER_TOKEN_BEDROCK", "AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY",
}

// miniMaxDisableEvalCaptureEnv turns off mcode's step-report upload, which is
// separate from the dataContribution switch in the managed config. The agent
// sets it on itself so every mcode run inherits it, whatever the pod spec says.
const miniMaxDisableEvalCaptureEnv = "MCODE_DISABLE_EVAL_CAPTURE"

// validateMiniMaxProxyClientEnv is the minimax-code counterpart of
// validateClaudeProxyClientEnv (AC-G3): the CLI container must point at the
// loopback proxy with the placeholder, and must hold no credential of any kind
// — neither a provider key under any of the names mcode or Claude would read,
// nor claude-code's plugin bootstrap token, which this type has no use for.
func validateMiniMaxProxyClientEnv() error {
	if os.Getenv("ANTHROPIC_BASE_URL") != claudeProxyBaseURL {
		return errors.New("minimax-code must use the localhost credential proxy URL")
	}
	if os.Getenv("ANTHROPIC_AUTH_TOKEN") != claudeProxyPlaceholderToken {
		return errors.New("minimax-code must use the non-secret credential proxy placeholder")
	}
	for _, name := range miniMaxCredentialEnv {
		if os.Getenv(name) != "" {
			return fmt.Errorf("minimax-code container must not receive %s", name)
		}
	}
	return nil
}

// newMiniMaxWorkloadFromEnv builds the minimax-code agent from the pod
// environment the control plane injects (AC-G3).
func newMiniMaxWorkloadFromEnv(logger *slog.Logger, restoreMode bool) (*claudeWorkload, error) {
	if err := validateMiniMaxProxyClientEnv(); err != nil {
		return nil, err
	}
	if err := os.Setenv(miniMaxDisableEvalCaptureEnv, "1"); err != nil {
		return nil, err
	}
	runTimeout, err := durationEnv("CLAUDE_CODE_RUN_TIMEOUT", defaultClaudeRunTimeout)
	if err != nil {
		return nil, err
	}
	stateDir := env("CLAUDE_CODE_STATE_DIR", defaultClaudeStateDir)
	model := env(miniMaxModelEnv, platformDefaultModel)
	cli, err := newMiniMaxCLI(stateDir, model, claudeProxyBaseURL, claudeProxyPlaceholderToken)
	if err != nil {
		return nil, err
	}
	return newClaudeWorkload(claudeConfig{
		StateDir:    stateDir,
		Model:       model,
		Binary:      env(miniMaxBinaryEnv, defaultMiniMaxBinary),
		RestoreMode: restoreMode,
		Runner:      execCommandRunner{},
		Logger:      logger,
		Redact:      miniMaxRedactionLiterals(),
		RunTimeout:  runTimeout,
		CLI:         cli,
	})
}

func miniMaxRedactionLiterals() []string {
	literals := credentialLiteralsFromEnv()
	for _, name := range miniMaxCredentialEnv {
		literals = append(literals, os.Getenv(name))
	}
	return normaliseRedactionLiterals(literals)
}

// miniMaxStreamProjector turns `mcode exec --output-format stream-json` into the
// user-facing text stream (AC-G2), the counterpart of claudeStreamProjector.
// Only the assistant's own message text is projected: each agent_message item
// streams contentDelta pieces in order and closes with item.completed. Reasoning
// and tool-call items are not user output, and a failed turn needs nothing
// here because mcode also reports it on stderr, which the session already
// keeps as diagnostics. A non-JSON line is passed through unchanged.
type miniMaxStreamProjector struct {
	dst io.Writer
	buf []byte

	// openItem is the agent_message whose text is being written.
	openItem string
	// streamed records agent_message items that produced at least one delta,
	// so a completed record carrying the full content is not projected twice.
	streamed map[string]bool

	messageHasText bool
	messageNewline bool
}

func newMiniMaxStreamProjector(dst io.Writer) *miniMaxStreamProjector {
	return &miniMaxStreamProjector{dst: dst, streamed: map[string]bool{}}
}

func (p *miniMaxStreamProjector) Write(chunk []byte) (int, error) {
	originalLen := len(chunk)
	p.buf = append(p.buf, chunk...)
	for {
		newline := bytes.IndexByte(p.buf, '\n')
		if newline < 0 {
			break
		}
		line := append([]byte(nil), p.buf[:newline]...)
		p.buf = p.buf[newline+1:]
		if err := p.projectLine(line, true); err != nil {
			return 0, err
		}
	}
	return originalLen, nil
}

func (p *miniMaxStreamProjector) Close() error {
	if len(p.buf) != 0 {
		line := append([]byte(nil), p.buf...)
		p.buf = nil
		if err := p.projectLine(line, false); err != nil {
			return err
		}
	}
	return p.finishMessage()
}

// miniMaxStreamEnvelope keeps every field it does not need as raw JSON, so a
// record whose shape it does not expect still decodes and is then dropped.
// Only a line that is not JSON at all is treated as a diagnostic: a valid
// record that merely failed to decode must never reach the session verbatim,
// because tool records carry tool output (and could carry anything).
type miniMaxStreamEnvelope struct {
	Type string          `json:"type"`
	Item json.RawMessage `json:"item"`
}

type miniMaxStreamItem struct {
	ID           string `json:"id"`
	Type         string `json:"type"`
	ContentDelta string `json:"contentDelta"`
	Content      string `json:"content"`
}

// agentMessage returns the record's agent_message item, or nil for anything
// else, including an agent_message whose text fields are not strings.
func (e miniMaxStreamEnvelope) agentMessage() *miniMaxStreamItem {
	if len(e.Item) == 0 {
		return nil
	}
	var kind struct {
		Type string `json:"type"`
	}
	if json.Unmarshal(e.Item, &kind) != nil || kind.Type != "agent_message" {
		return nil
	}
	var item miniMaxStreamItem
	if json.Unmarshal(e.Item, &item) != nil {
		return nil
	}
	return &item
}

func (p *miniMaxStreamProjector) projectLine(line []byte, hadNewline bool) error {
	var envelope miniMaxStreamEnvelope
	if len(line) == 0 || !json.Valid(line) {
		if _, err := p.dst.Write(line); err != nil {
			return err
		}
		if hadNewline {
			_, err := p.dst.Write([]byte{'\n'})
			return err
		}
		return nil
	}
	if json.Unmarshal(line, &envelope) != nil {
		return nil
	}
	item := envelope.agentMessage()
	if item == nil {
		if envelope.Type == "turn.completed" || envelope.Type == "exec.completed" {
			return p.finishMessage()
		}
		return nil
	}
	switch envelope.Type {
	case "item.started", "item.updated":
		if item.ContentDelta == "" {
			return nil
		}
		if err := p.openMessage(item.ID); err != nil {
			return err
		}
		p.streamed[item.ID] = true
		return p.writeText(item.ContentDelta)
	case "item.completed":
		if !p.streamed[item.ID] && item.Content != "" {
			if err := p.openMessage(item.ID); err != nil {
				return err
			}
			if err := p.writeText(item.Content); err != nil {
				return err
			}
		}
		delete(p.streamed, item.ID)
		if p.openItem == item.ID {
			p.openItem = ""
			return p.finishMessage()
		}
	}
	return nil
}

// openMessage ends the previous message before a different one starts, so two
// messages never run together on one line.
func (p *miniMaxStreamProjector) openMessage(id string) error {
	if p.openItem == id {
		return nil
	}
	if err := p.finishMessage(); err != nil {
		return err
	}
	p.openItem = id
	return nil
}

func (p *miniMaxStreamProjector) writeText(text string) error {
	if _, err := io.WriteString(p.dst, text); err != nil {
		return err
	}
	p.messageHasText = true
	p.messageNewline = text[len(text)-1] == '\n'
	return nil
}

func (p *miniMaxStreamProjector) finishMessage() error {
	if p.messageHasText && !p.messageNewline {
		if _, err := p.dst.Write([]byte{'\n'}); err != nil {
			return err
		}
	}
	p.messageHasText = false
	p.messageNewline = false
	return nil
}
